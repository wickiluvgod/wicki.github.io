const languageButton = document.querySelector("#languageButton");
const languageMenu = document.querySelector("#languageMenu");
const menuToggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".nav");

languageButton.addEventListener("click", () => languageMenu.classList.toggle("open"));
document.addEventListener("click", e => {
  if (!e.target.closest(".language-picker")) languageMenu.classList.remove("open");
});
document.querySelectorAll("[data-lang]").forEach(button => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
    languageMenu.classList.remove("open");
  });
});

function setLanguage(lang) {
  const dict = translations[lang];
  document.documentElement.lang = lang;
  languageButton.textContent = lang.toUpperCase() + " ▾";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.innerHTML = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });
  document.querySelector("#formMessage").textContent = "";
  localStorage.setItem("autoShineLanguage", lang);
}

menuToggle.addEventListener("click", () => nav.classList.toggle("open"));
document.querySelectorAll(".nav a").forEach(link => {
  link.addEventListener("click", () => nav.classList.remove("open"));
});

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) entry.target.classList.add("visible");
  });
}, {threshold:.12});
document.querySelectorAll(".reveal").forEach(el => observer.observe(el));

document.querySelector("#bookingForm").addEventListener("submit", event => {
  event.preventDefault();
  const lang = localStorage.getItem("autoShineLanguage") || "en";
  document.querySelector("#formMessage").textContent = translations[lang].success;
  event.target.reset();
});

setLanguage(localStorage.getItem("autoShineLanguage") || "en");
